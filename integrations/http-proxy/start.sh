#!/bin/bash
# =============================================================================
# FluxVPN HTTP Proxy (Squid) Startup Script (API-based Auth)
# =============================================================================
# Called by entrypoint-wrapper.sh after successful deployment validation.
#
# Auth flow:
#   1. Custom Squid auth helper validates each request against Worker API
#   2. Background sync daemon maintains htpasswd file as backup
# =============================================================================

set -e

log_info() {
    echo -e "\033[0;32m[HTTP-Proxy]\033[0m $1"
}

log_error() {
    echo -e "\033[0;31m[HTTP-Proxy]\033[0m $1"
}

# Check if we were validated by the entrypoint wrapper
if [ "$FLUXVPN_VALIDATED" != "true" ]; then
    log_error "Container not validated by FluxVPN. Exiting."
    exit 1
fi

log_info "Starting HTTP Proxy service (API-based auth)..."
log_info "Protocol: $FLUXVPN_PROTOCOL"
log_info "Deployment ID: $FLUXVPN_DEPLOYMENT_ID"

# Initialize telemetry sidecar
TELEMETRY_PORT="${TELEMETRY_PORT:-9095}"
source /usr/local/bin/telemetry_helpers.sh
init_telemetry
log_info "Telemetry initialized on port $TELEMETRY_PORT"

# Extract configuration from FLUXVPN_CONFIG
PROXY_PORT=$(echo "$FLUXVPN_CONFIG" | jq -r '.port // 3128')

log_info "Port: $PROXY_PORT"

# =============================================================================
# Set up authentication
# =============================================================================

# Create initial htpasswd with deployment user (fallback)
PROXY_USERNAME=$(echo "$FLUXVPN_CONFIG" | jq -r '.username // empty')
PROXY_PASSWORD=$(echo "$FLUXVPN_CONFIG" | jq -r '.password // empty')

mkdir -p /etc/squid
if [ -n "$PROXY_USERNAME" ] && [ -n "$PROXY_PASSWORD" ]; then
    htpasswd -bc /etc/squid/passwd "$PROXY_USERNAME" "$PROXY_PASSWORD"
    log_info "Initial user created: $PROXY_USERNAME"
fi
chmod 644 /etc/squid/passwd

# Choose auth helper: API-based if INTERNAL_API_KEY is set, else htpasswd
if [ -n "$INTERNAL_API_KEY" ] && [ -x "/usr/local/bin/vpn_squid_auth.sh" ]; then
    AUTH_HELPER="/usr/local/bin/vpn_squid_auth.sh"
    log_info "Using API-based auth helper"
else
    # Fallback to standard htpasswd auth
    AUTH_HELPER=""
    for path in /usr/lib/squid/basic_ncsa_auth /usr/lib/squid3/basic_ncsa_auth /usr/lib64/squid/basic_ncsa_auth; do
        if [ -x "$path" ]; then
            AUTH_HELPER="$path"
            break
        fi
    done
    log_info "Using htpasswd auth helper: $AUTH_HELPER"
fi

if [ -z "$AUTH_HELPER" ]; then
    log_error "No auth helper available!"
    exit 1
fi

# =============================================================================
# Start background user sync daemon (keeps htpasswd updated as backup)
# =============================================================================
if [ -n "$INTERNAL_API_KEY" ]; then
    log_info "Starting user sync daemon..."
    /usr/local/bin/vpn_auth_sync.sh &
    SYNC_PID=$!
    log_info "Sync daemon started (PID: $SYNC_PID)"
fi

# =============================================================================
# Generate Squid configuration
# =============================================================================
cat > /etc/squid/squid.conf << EOF
# FluxVPN HTTP Proxy Configuration
# Generated by FluxVPN deployment system (API-based auth)

# Basic settings
http_port $PROXY_PORT

# Access control
acl localnet src all
acl SSL_ports port 443
acl Safe_ports port 80
acl Safe_ports port 21
acl Safe_ports port 443
acl Safe_ports port 70
acl Safe_ports port 210
acl Safe_ports port 1025-65535
acl Safe_ports port 280
acl Safe_ports port 488
acl Safe_ports port 591
acl Safe_ports port 777
acl CONNECT method CONNECT

# Authentication
auth_param basic program $AUTH_HELPER
auth_param basic children 5
auth_param basic realm FluxVPN Proxy
auth_param basic credentialsttl 2 hours
acl authenticated proxy_auth REQUIRED

# Access rules
http_access deny !Safe_ports
http_access deny CONNECT !SSL_ports
http_access allow authenticated
http_access deny all

# Caching
cache_mem 256 MB
maximum_object_size 100 MB
cache_dir ufs /var/spool/squid 1000 16 256

# Logging
access_log stdio:/var/log/squid/access.log squid
cache_log /var/log/squid/cache.log

# Privacy
forwarded_for delete
request_header_access X-Forwarded-For deny all

# Timeouts
connect_timeout 60 seconds
read_timeout 15 minutes
request_timeout 5 minutes

# Performance
dns_nameservers 8.8.8.8 8.8.4.4
EOF

log_info "Squid config generated"

# Create required directories
mkdir -p /var/spool/squid /var/log/squid /run/squid
chown -R proxy:proxy /var/spool/squid /var/log/squid /run/squid

# Clean up any stale PID file
rm -f /run/squid.pid

# Initialize the cache on every start. -N keeps `squid -z` in the foreground so
# it finishes before squid starts (a daemonized -z plus `sleep 1` raced on slow
# nodes), and -z only creates missing swap dirs, so a half-built cache from an
# earlier crash is repaired instead of failing forever.
log_info "Initializing Squid cache..."
squid -z -N 2>/dev/null || true
rm -f /run/squid.pid

# Start Squid in foreground
log_info "Starting Squid on port $PROXY_PORT (API-based auth)..."
exec squid -N -d 1
